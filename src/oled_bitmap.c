static const uint8_t *bitmap_rows(char c){
    if(c>='a'&&c<='z') c=(char)(c-'a'+'A');
    for(size_t i=0;i<sizeof(bitmap_font)/sizeof(bitmap_font[0]);i++){
        if(bitmap_font[i].ch==(unsigned char)c)return bitmap_font[i].rows;
    }
    return bitmap_font[0].rows;
}
int oled_bitmap_width(const char *s){return (int)strlen(s)*6-1;}
void oled_bitmap_text_on(oled_t *o,const char *s,int x,int y,int on){
    for(;*s;s++,x+=6){
        const uint8_t *rows=bitmap_rows(*s);
        for(int r=0;r<7;r++)for(int col=0;col<5;col++){
            if(rows[r] & (1U << (4-col))) oled_pixel(o,x+col,y+r,on);
        }
    }
}
void oled_bitmap_text(oled_t *o,const char *s,int x,int y){oled_bitmap_text_on(o,s,x,y,1);}
